// The library's startup self-check (Sources/ExactJPEG/SelfCheck.swift):
//   ejm selfcheck-gen [path]   build the built-in cases with libjpeg-turbo and write SelfCheckData.swift
//                              (default Sources/ExactJPEG/SelfCheckData.swift); deterministic, test.sh checks it is fresh
//   ejm selfcheck              run the self-check in this process: pass or fail, and the time it took
//   ejm selfcheck-child <mode> helper processes for `ejm api-check self-check` (forced, concurrent)

private struct DecodeSpec { let name: String; let w: Int, h: Int, quality: Int, samp: Int, restartMCUs: Int; let gray: Bool; let format: PixelFormat
    var baseline = true }
private struct EncodeSpec { let name: String; let w: Int, h: Int, channels: Int, rowBytes: Int, quality: Int, samp: Int; let twoPass: Bool }

private let decodeSpecs = [
    DecodeSpec(name: "decode 4:2:0 with restart markers", w: 61, h: 45, quality: 90, samp: 2, restartMCUs: 2, gray: false, format: .rgb),
    DecodeSpec(name: "decode 4:2:0 without restarts", w: 80, h: 64, quality: 90, samp: 2, restartMCUs: 0, gray: false, format: .rgb),
    DecodeSpec(name: "decode 4:2:2", w: 48, h: 32, quality: 90, samp: 1, restartMCUs: 0, gray: false, format: .bgr),
    DecodeSpec(name: "decode 4:4:4", w: 40, h: 24, quality: 85, samp: 0, restartMCUs: 0, gray: false, format: .rgba),
    DecodeSpec(name: "decode gray", w: 37, h: 29, quality: 80, samp: 0, restartMCUs: 0, gray: true, format: .gray),
    DecodeSpec(name: "decode 4:4:0", w: 40, h: 48, quality: 90, samp: 3, restartMCUs: 0, gray: false, format: .rgb),
    // q8 without force_baseline: quantisers up to 756, which libjpeg-turbo writes as a 16-bit DQT (SOF1)
    DecodeSpec(name: "decode 16-bit quantisation tables", w: 40, h: 32, quality: 8, samp: 2, restartMCUs: 0, gray: false,
               format: .bgra, baseline: false),
]
private let encodeSpecs = [
    EncodeSpec(name: "encode fused", w: 64, h: 48, channels: 3, rowBytes: 192, quality: 90, samp: 2, twoPass: false),
    EncodeSpec(name: "encode two-pass", w: 45, h: 31, channels: 4, rowBytes: 45 * 4 + 12, quality: 75, samp: 0, twoPass: true),
]

private func specPixels(_ w: Int, _ h: Int, gray: Bool) -> [UInt8] {
    let rgb = SelfCheckTesting.pixels(width: w, height: h, channels: 3, rowBytes: w * 3)
    return gray ? stride(from: 0, to: rgb.count, by: 3).map { rgb[$0] } : rgb
}

private func sha256Hex(_ b: UnsafeRawBufferPointer) -> String { SHA256.hash(data: b).map { String(format: "%02x", $0) }.joined() }

/// The JPEG of a built-in decode case, rebuilt with libjpeg-turbo (api-check uses it to inspect the sync case).
func selfCheckCaseJPEG(_ name: String) -> Data? {
    guard let c = decodeSpecs.first(where: { $0.name == name }) else { return nil }
    return Turbo.encode(specPixels(c.w, c.h, gray: c.gray), c.w, c.h, gray: c.gray, quality: c.quality, samp: c.samp, restartMCUs: c.restartMCUs,
                        baseline: c.baseline)
}

func runSelfCheckGen(path: String) -> Bool {
    let fmtName: [PixelFormat: String] = [.rgb: ".rgb", .bgr: ".bgr", .gray: ".gray", .rgba: ".rgba", .bgra: ".bgra"]
    let sub = [".s444", ".s422", ".s420"]
    var s = "// GENERATED by `ejm selfcheck-gen` (Sources/ejm/SelfCheckGen.swift) with \(Turbo.version). Do not edit.\n"
    s += "// The built-in cases of the startup self-check (SelfCheck.swift). Inputs are synthetic\n"
    s += "// (SelfCheckTesting.pixels); every JPEG and every SHA-256 below comes from libjpeg-turbo, not from the GPU.\n"
    s += "enum SelfCheckData {\n    static let decodeCases: [SelfCheckDecodeCase] = [\n"
    var total = 0
    for c in decodeSpecs {
        let px = specPixels(c.w, c.h, gray: c.gray)
        let jpeg = Turbo.encode(px, c.w, c.h, gray: c.gray, quality: c.quality, samp: c.samp, restartMCUs: c.restartMCUs, baseline: c.baseline)
        guard let ref = turboDecode(jpeg, c.format) else { print("libjpeg-turbo failed to decode \(c.name)"); return false }
        total += jpeg.count
        let b64 = jpeg.base64EncodedString()
        let lines = stride(from: 0, to: b64.count, by: 100).map { i -> String in
            let a = b64.index(b64.startIndex, offsetBy: i), e = b64.index(a, offsetBy: min(100, b64.count - i))
            return "            " + b64[a..<e]
        }
        let hash = ref.withUnsafeBytes { sha256Hex($0) }
        s += "        SelfCheckDecodeCase(name: \"\(c.name)\", format: \(fmtName[c.format]!), sha256: \"\(hash)\", jpeg: \"\"\"\n"
        s += lines.joined(separator: "\n") + "\n            \"\"\"),\n"
        let s0 = (try? jpeg.withUnsafeBytes { try parseJPEGHeader($0) })?.scanStart ?? 0
        print("\(c.name): \(jpeg.count) bytes, \(jpeg.count - s0) of entropy-coded data (\(((jpeg.count - s0) * 8 + 2047) / 2048) chunks of 2048 bits, the default below 256 KB; \(((jpeg.count - s0) * 8 + 4095) / 4096) of 4096)")
    }
    s += "    ]\n    static let encodeCases: [SelfCheckEncodeCase] = [\n"
    for c in encodeSpecs {
        let jpeg = Turbo.encode(specPixels(c.w, c.h, gray: false), c.w, c.h, quality: c.quality, samp: c.samp)
        let hash = jpeg.withUnsafeBytes { sha256Hex($0) }
        s += "        SelfCheckEncodeCase(name: \"\(c.name)\", width: \(c.w), height: \(c.h), channels: \(c.channels), rowBytes: \(c.rowBytes), "
        s += "quality: \(c.quality),\n                            subsampling: \(sub[c.samp]), twoPass: \(c.twoPass), sha256: \"\(hash)\"),\n"
        print("\(c.name): libjpeg-turbo file \(jpeg.count) bytes")
    }
    s += "    ]\n}\n"
    print("embedded JPEG data: \(total) bytes (\(s.utf8.count) bytes of Swift source)")
    do { try s.write(toFile: path, atomically: true, encoding: .utf8) } catch { print("cannot write \(path): \(error)"); return false }
    print("wrote \(path)")
    return true
}

func runSelfCheckCommand() -> Bool {
    let t0 = now()
    let ctx = MetalContext.shared
    let t1 = now()
    let rd = ctx.selfCheck(decode: true, encode: false)
    let t2 = now()
    let re = ctx.selfCheck(decode: false, encode: true)
    let t3 = now()
    print("Metal context (shader library compile): \(fmt((t1 - t0) * 1000, 1)) ms")
    print("decode half (\(SelfCheckTesting.decodeRuns) run): \(fmt((t2 - t1) * 1000, 1)) ms; encode half (\(SelfCheckTesting.encodeRuns) run): \(fmt((t3 - t2) * 1000, 1)) ms")
    if let r = rd ?? re { print("self-check: FAIL: \(r)"); return false }
    print("self-check: pass on \(ctx.device.name), \(fmt((t3 - t1) * 1000, 1)) ms")
    return true
}

// ---- helper processes for `ejm api-check self-check` ----

/// a small libjpeg-turbo JPEG for the child checks
private func childJPEG() -> Data { Turbo.encode(corpusContent(203, 97, "smooth", 41), 203, 97, quality: 90, samp: 2) }

/// forced: run with EJM_SELFCHECK_FAIL=1. Every public path must decline or throw with the self-check reason and
/// leave the output untouched; the check runs once. Prints one OK / FAIL line per item; exit 0 when all are OK.
/// concurrent: 10 threads make their first decode at the same time; the check must run exactly once.
func runSelfCheckChild(_ mode: String) -> Bool {
    var bad = 0
    func check(_ c: Bool, _ what: String) { print("\(c ? "OK" : "FAIL") \(what)"); if !c { bad += 1 } }
    let jpeg = childJPEG()
    let ref = turboDecode(jpeg, .rgb)!
    switch mode {
    case "forced":
        let marker = "self-check failed on "
        let dec = Decoder()
        let img = dec.decode(jpeg)
        check(img == nil && dec.reason?.hasPrefix(marker) == true && dec.reason?.contains("EJM_SELFCHECK_FAIL") == true,
              "Swift decode declines: \(dec.reason ?? "no reason")")
        let ob = dec.ctx.device.makeBuffer(length: ref.count, options: .storageModeShared)!
        memset(ob.contents(), 0xA5, ref.count)
        let img2 = jpeg.withUnsafeBytes { dec.decode(bytes: $0, output: ob) }
        check(img2 == nil && UnsafeRawBufferPointer(start: ob.contents(), count: ref.count).allSatisfy { $0 == 0xA5 },
              "Swift decode(bytes:output:) declines, output untouched")
        let tmp = NSTemporaryDirectory() + "ejm-selfcheck-\(getpid()).jpg"
        try! jpeg.write(to: URL(fileURLWithPath: tmp))
        check(dec.decode(path: tmp) == nil && dec.reason?.hasPrefix(marker) == true, "Swift decode(path:) declines")
        try? FileManager.default.removeItem(atPath: tmp)
        let enc = Encoder()
        let px = corpusContent(64, 48, "smooth", 3)
        do { _ = try px.withUnsafeBytes { try enc.encode(bytes: $0, width: 64, height: 48) }; check(false, "Swift encode throws (it returned)") }
        catch let e as SelfCheckFailed { check(e.description.hasPrefix(marker) && e.description == dec.reason, "Swift encode throws SelfCheckFailed: \(e.description)") }
        catch { check(false, "Swift encode throws SelfCheckFailed (threw \(type(of: error)))") }
        do { _ = try enc.encodeBatch([EncodeJob(buffer: sharedBuffer(px, enc.ctx.device), width: 64, height: 48)]); check(false, "encodeBatch throws") }
        catch { check(error is SelfCheckFailed, "encodeBatch throws SelfCheckFailed") }
        let cd = ejm_decoder_create()!
        let page = Int(getpagesize())
        let cap = (ref.count + page) / page * page
        let p = UnsafeMutableRawPointer.allocate(byteCount: cap, alignment: page)
        for (label, o, oc) in [("zero-copy", p, cap), ("copy", p + 1, cap - 1)] {
            memset(p, 0xA5, cap)
            var w: Int32 = 0, h: Int32 = 0
            let r = jpeg.withUnsafeBytes { ejm_decode(cd, $0.baseAddress!.assumingMemoryBound(to: UInt8.self), jpeg.count, 0, o.assumingMemoryBound(to: UInt8.self), oc, &w, &h) }
            let why = ejm_decoder_reason(cd).map { String(cString: $0) } ?? ""
            check(r == 1 && why == dec.reason, "ejm_decode (\(label)) returns EJM_DECLINED with the reason: \(r), \(why)")
            check(UnsafeRawBufferPointer(start: p, count: cap).allSatisfy { $0 == 0xA5 }, "ejm_decode (\(label)): out untouched")
        }
        p.deallocate()
        var view: UnsafePointer<UInt8>? = nil
        var w: Int32 = 0, h: Int32 = 0, c: Int32 = 0
        let rv = jpeg.withUnsafeBytes { ejm_decode_view(cd, $0.baseAddress!.assumingMemoryBound(to: UInt8.self), jpeg.count, 0, &view, &w, &h, &c) }
        check(rv == 1 && view == nil && String(cString: ejm_decoder_reason(cd)!).hasPrefix(marker), "ejm_decode_view returns EJM_DECLINED")
        ejm_decoder_destroy(cd)
        let ce = ejm_encoder_create()!
        var out: UnsafeMutablePointer<UInt8>? = nil
        var len = 0
        let re = px.withUnsafeBufferPointer { ejm_encode(ce, $0.baseAddress, 64, 48, 3, 192, 90, 2, &out, &len) }
        check(re == -1 && out == nil && String(cString: ejm_encoder_error(ce)!).hasPrefix(marker), "ejm_encode returns EJM_ERROR with the reason")
        ejm_encoder_destroy(ce)
        check(SelfCheckTesting.decodeRuns == 1 && SelfCheckTesting.encodeRuns == 0,
              "the check ran once, not once per call (decode half \(SelfCheckTesting.decodeRuns), encode half \(SelfCheckTesting.encodeRuns))")
    case "concurrent":
        let n = 10
        let rp = UnsafeMutableBufferPointer<Bool>.allocate(capacity: n)
        rp.initialize(repeating: false)
        let results = Unchecked(rp)
        let go = DispatchSemaphore(value: 0), ready = DispatchGroup(), done = DispatchGroup()
        for i in 0..<n {
            ready.enter(); done.enter()
            Thread {
                let dec = Decoder()          // MetalContext.shared, created by the first thread to get here
                ready.leave()
                go.wait()
                let img = dec.decode(jpeg)
                results.value[i] = img.map { $0.bytes.elementsEqual(ref) } ?? false
                done.leave()
            }.start()
        }
        ready.wait()
        check(SelfCheckTesting.decodeRuns == 0, "no check before the first decode: \(SelfCheckTesting.decodeRuns)")
        for _ in 0..<n { go.signal() }
        done.wait()
        check(rp.allSatisfy { $0 }, "\(n) concurrent first decodes all exact")
        check(SelfCheckTesting.decodeRuns == 1, "\(n) concurrent first decodes ran the decode half once: \(SelfCheckTesting.decodeRuns)")
        check(SelfCheckTesting.encodeRuns == 0, "decoding alone does not run the encode half: \(SelfCheckTesting.encodeRuns)")
        // the same for the first encodes
        let px = corpusContent(64, 48, "smooth", 3)
        let eref = Turbo.encode(px, 64, 48, quality: 75, samp: 2)
        rp.update(repeating: false)
        let go2 = DispatchSemaphore(value: 0), ready2 = DispatchGroup(), done2 = DispatchGroup()
        for i in 0..<n {
            ready2.enter(); done2.enter()
            Thread {
                let enc = Encoder()
                ready2.leave()
                go2.wait()
                let out = try? px.withUnsafeBytes { try enc.encode(bytes: $0, width: 64, height: 48) }
                results.value[i] = out == eref
                done2.leave()
            }.start()
        }
        ready2.wait()
        for _ in 0..<n { go2.signal() }
        done2.wait()
        check(rp.allSatisfy { $0 }, "\(n) concurrent first encodes all identical to libjpeg-turbo")
        check(SelfCheckTesting.encodeRuns == 1 && SelfCheckTesting.decodeRuns == 1,
              "\(n) concurrent first encodes ran the encode half once: \(SelfCheckTesting.encodeRuns) (decode half \(SelfCheckTesting.decodeRuns))")
        rp.deallocate()
    default:
        print("unknown mode \(mode)"); return false
    }
    return bad == 0
}
