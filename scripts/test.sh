#!/bin/bash
# Full test run (about 3 minutes on an M1 Max: 178 s on 2026-11-18, after the build): docs check, generated-file freshness, self-check, exactness corpora
# (and the exactness range: the encoder's two-pass path, two more decoder chunk settings; both corpora with
# per-stage timing on), API checks, the opt-in packed path (also under shader validation), fuzzing,
# shader-validated fuzzing, the encoder under shader validation (corpus and retries, both paths), mixed-size
# sequences (ejm mixed), the decline corpus (ejm decline-corpus), the encoder fuzz (ejm encode-fuzz), C and Swift
# examples, and finally the exactness record of this run (ejm exactness: work/test-<date>/exactness.json).
# Exits non-zero on any failure. Logs and fuzz summaries go to work/test-<date>/ (not committed).
# FUZZ_ITERS (default 50000), SV_ITERS (default 5000) and ENC_FUZZ_ITERS (default 5000) set the fuzz lengths;
# the defaults are also the minimums `ejm exactness` accepts for the record (it reads the *_DEFAULT line below), so
# a shorter run passes every step but ends with the record refused.
# The target is libjpeg-turbo 3.2.0. With another version loaded (the M4 has 3.2.1) the run goes on with a loud
# warning; the proof of 3.2.0 exactness there is the pinned manifest check, which must pass with its full counts.
set -euo pipefail
FUZZ_DEFAULT=50000; SV_DEFAULT=5000; ENC_FUZZ_DEFAULT=5000
source "$(dirname "$0")/env.sh"
out="work/test-$(date +%Y%m%d-%H%M%S)"; mkdir -p "$out"
echo "== docs cover every shipped symbol"; ./scripts/check-docs.sh
cp Sources/ExactJPEG/ShaderSource.swift "$out/ShaderSource.before"
./scripts/gen-shaders.sh
cmp -s Sources/ExactJPEG/ShaderSource.swift "$out/ShaderSource.before" || { echo "FAIL: ShaderSource.swift was stale (now regenerated; commit it)"; exit 1; }
swift build -c release
swift build -c release --package-path Tools
E=Tools/.build/release/ejm
# the libjpeg-turbo this process loads (from its resolved path; the headers' LIBJPEG_TURBO_VERSION can differ)
echo "== libjpeg-turbo reference"; $E turbo-version | tee "$out/turbo-version.log"
rt="$(awk '/^runtime /{print $2}' "$out/turbo-version.log")"
if [ "$rt" != "3.2.0" ]; then
  for _ in 1 2 3; do echo "WARNING: libjpeg-turbo $rt is loaded, not 3.2.0 (the exactness target)"; done
  echo "WARNING: comparisons with the local libjpeg-turbo below are against $rt; the 3.2.0 proof is the pinned"
  echo "WARNING: manifest check (testdata/manifest-libjpeg-turbo-3.2.0.json), required below with its full counts"
fi
rec="$out/record"    # where the steps of the exactness record write their counts (ejm exactness)
echo "== self-check data fresh (ejm selfcheck-gen), self-check passes"
# the embedded data is generated by libjpeg-turbo 3.2.0 (the manifest's target); other versions may write other
# JPEG bytes, so the freshness check only runs there. The self-check itself runs everywhere (stored hashes).
if [ "$rt" = "3.2.0" ]; then
  cp Sources/ExactJPEG/SelfCheckData.swift "$out/SelfCheckData.before"
  $E selfcheck-gen > "$out/selfcheck-gen.log"
  cmp -s Sources/ExactJPEG/SelfCheckData.swift "$out/SelfCheckData.before" || { echo "FAIL: SelfCheckData.swift was stale (now regenerated; rebuild and commit it)"; exit 1; }
else
  echo "self-check data freshness: skipped (libjpeg-turbo $rt loaded, data is from 3.2.0)"
fi
$E selfcheck | tail -1
echo "== decoder corpus";  $E corpus --record="$rec"        | tee "$out/corpus.log"        | tail -1
echo "== encoder corpus";  $E encode-corpus --record="$rec" | tee "$out/encode-corpus.log" | tail -1
# Exactness range: every value a tuner can pick must give the same bytes. Both encoder entropy paths (the device
# default above is one of them: DeviceProfile.encoderPath), and the decoder corpus at two more chunk settings with
# the same declined set.
for fb in 0 2000000; do
  echo "== encoder corpus, EJM_FUSED_MAX_BLOCKS=$fb ($([ $fb = 0 ] && echo two-pass || echo single-pass))"
  EJM_FUSED_MAX_BLOCKS=$fb $E encode-corpus | tee "$out/encode-corpus-fused$fb.log" | tail -1
  grep -q "identical files 869, different 0" "$out/encode-corpus-fused$fb.log" || { echo "FAIL: encoder corpus at EJM_FUSED_MAX_BLOCKS=$fb"; exit 1; }
done
want="$(grep '^declined set:' "$out/corpus.log")"
for cs in 2048/3 8192/15; do
  echo "== decoder corpus, EJM_CHUNK_BITS=${cs%/*} EJM_NCP=${cs#*/}"
  EJM_CHUNK_BITS=${cs%/*} EJM_NCP=${cs#*/} $E corpus | tee "$out/corpus-${cs%/*}.log" | tail -1
  grep -q "^exact: 582, declined as expected: 36, wrong: 0, unexpected decline/accept: 0" "$out/corpus-${cs%/*}.log" \
    || { echo "FAIL: decoder corpus at chunk setting $cs"; exit 1; }
  [ "$(grep '^declined set:' "$out/corpus-${cs%/*}.log")" = "$want" ] || { echo "FAIL: declined set differs at chunk setting $cs"; exit 1; }
done
# Per-stage timing on (EJM_TRACE=stages: one compute encoder per stage, Decoder/Encoder.recordStages) must give
# the same bytes; the trace lines go to stderr, into the logs.
echo "== decoder corpus and encoder corpus, EJM_TRACE=stages"
EJM_TRACE=stages $E corpus 2> "$out/corpus-stages.trace" | tee "$out/corpus-stages.log" | tail -1
grep -q "^exact: 582, declined as expected: 36, wrong: 0, unexpected decline/accept: 0" "$out/corpus-stages.log" \
  || { echo "FAIL: decoder corpus with EJM_TRACE=stages"; exit 1; }
[ "$(grep '^declined set:' "$out/corpus-stages.log")" = "$want" ] || { echo "FAIL: declined set differs with EJM_TRACE=stages"; exit 1; }
EJM_TRACE=stages $E encode-corpus 2> "$out/encode-corpus-stages.trace" | tee "$out/encode-corpus-stages.log" | tail -1
grep -q "identical files 869, different 0" "$out/encode-corpus-stages.log" || { echo "FAIL: encoder corpus with EJM_TRACE=stages"; exit 1; }
echo "trace lines with stages: $(grep -c ' stages unstuff ' "$out/corpus-stages.trace" || true) decodes, $(grep -c ' stages fill+' "$out/encode-corpus-stages.trace" || true) encodes"
echo "exactness range: encoder two-pass and single-pass 869/869 each; chunk settings 2048/3 and 8192/15 582 exact each, declined set identical ($want)"
echo "== manifest (fixed libjpeg-turbo 3.2.0 target)"; $E manifest check --record="$rec" | tee "$out/manifest.log" | tail -2
# the full counts, paired by name: every decodable file in both formats against the stored 3.2.0 hashes (none
# against a local libjpeg-turbo that writes other JPEG bytes), the 18 progressive files declined, every encoder case
grep -qx "manifest counts: decode exact vs manifest 582/582, vs local libjpeg-turbo 0; declined 36/36, unexpected accept 0; encode exact 864/864" "$out/manifest.log" \
  || { echo "FAIL: manifest check without its full counts (see $out/manifest.log)"; exit 1; }
[ "$rt" = "3.2.0" ] || echo "WARNING: libjpeg-turbo $rt loaded; 3.2.0 exactness rests on the manifest check above, which passed with full counts"
# Decline classes the docs promise (CMYK, YCCK, RGB-coded, multi-scan, arithmetic, 12-bit, lossless, hierarchical,
# fractional sampling) and the ones they say are taken (SOF1 8-bit, other integral factors): declined with a reason
# or identical to libjpeg-turbo, never different; the counts per class are in the log.
echo "== decline corpus (generated CMYK, YCCK, RGB, multi-scan, arithmetic, 12-bit, lossless, SOF1, ...)"
$E decline-corpus --record="$rec" > "$out/decline-corpus.log" || { cat "$out/decline-corpus.log"; echo "FAIL: decline corpus"; exit 1; }
tail -1 "$out/decline-corpus.log"
grep -qx "decline corpus: 60 files, 120 decodes: declined 84, exact 36, wrong 0, declined without a reason 0, against the docs 0, generator problems 0" "$out/decline-corpus.log" \
  || { grep "class " "$out/decline-corpus.log"; echo "FAIL: decline corpus counts changed (see $out/decline-corpus.log)"; exit 1; }
echo "== API checks (formats, C API, output:, ICC/EXIF, tuning, the 2026-11-16 fixes)"; $E api-check | tee "$out/api-check.log" | tail -1
# a case that cannot run on this machine (e.g. encoder-limits span-real without a 6 GB sparse mapping) is SKIPPED,
# not passed: the count is shown here, never hidden
grep '^api-check: skipped cases' "$out/api-check.log"
# The opt-in packed path (Decoder.decodeAndPack / decode(packed:)): the format's test vectors, forged index words
# (flag, guard bands, fallback) and the decoder corpus through it, which must give the default run's counts.
echo "== packed path (opt-in): vectors, forged index words, corpus"; $E packed-check | tee "$out/packed-check.log" | tail -1
grep -q "^packed exact: 582, declined as expected: 36, wrong: 0, unexpected decline/accept: 0" "$out/packed-check.log" \
  || { echo "FAIL: decoder corpus through the packed path"; exit 1; }
# the fuzzers fail on any finding and when fewer than 10% of the mutated files decode exactly (an all-decline
# regression); about 20% do
echo "== fuzz";            $E fuzz "$out/fuzz" "${FUZZ_ITERS:-$FUZZ_DEFAULT}" "${FUZZ_SEED:-1}" > "$out/fuzz.log" \
  || { grep -E "FINDING|^FAIL|^fuzz:" "$out/fuzz.log" | head -20; echo "FAIL: fuzz (see $out/fuzz.log)"; exit 1; }
grep "^fuzz:" "$out/fuzz.log"
# Shader validation report wording varies by macOS: "Invalid Metal usage ..." (older), "Invalid device store/load at
# offset ..." (macOS 26), "Invalid store in 'device' or 'constant' address space ..."; every report carries "Error
# detected in <call>" and "GPU stack trace"; the API validation layer (MTL_DEBUG_LAYER) says "failed assertion".
# On macOS 26 the command buffer error stays nil, so match the log text. The two control runs below must match it.
# (No backslashes or double quotes: run.json carries it to ejm exactness as a JSON string.)
SV_PATTERN="Invalid (Metal usage|device|threadgroup|constant|texture|stack|resource|buffer|load|store|atomic|read|write)|Error detected in|GPU stack trace|failed assertion|MTLValidation|validation error"
echo "== fuzz with Metal shader validation"
MTL_SHADER_VALIDATION=1 MTL_SHADER_VALIDATION_REPORT_TO_STDERR=1 MTL_DEBUG_LAYER=1 \
  $E fuzz "$out/fuzz-sv" "${SV_ITERS:-$SV_DEFAULT}" 7 > "$out/fuzz-sv.log" 2>&1 \
  || { grep -E "FINDING|^FAIL|^fuzz:" "$out/fuzz-sv.log" | head -20; echo "FAIL: fuzz under shader validation (see $out/fuzz-sv.log)"; exit 1; }
grep "^fuzz:" "$out/fuzz-sv.log"
n=$(grep -cE "$SV_PATTERN" "$out/fuzz-sv.log" || true)
[ "$n" = "0" ] || { echo "FAIL: $n shader validation reports (see $out/fuzz-sv.log)"; exit 1; }
MTL_SHADER_VALIDATION=1 MTL_SHADER_VALIDATION_REPORT_TO_STDERR=1 $E oob-selfcheck > "$out/oob-selfcheck.log" 2>&1 || true
grep -qE "$SV_PATTERN" "$out/oob-selfcheck.log" \
  || { echo "FAIL: shader validation did not report a deliberate out-of-bounds write"; exit 1; }
echo "shader validation: 0 reports (and it does catch a deliberate out-of-bounds write)"
echo "== packed path: vectors and forged index words with Metal shader validation"
MTL_SHADER_VALIDATION=1 MTL_SHADER_VALIDATION_REPORT_TO_STDERR=1 MTL_DEBUG_LAYER=1 \
  $E packed-check vectors forged > "$out/packed-sv.log" 2>&1 || { echo "FAIL: packed-check under validation (see $out/packed-sv.log)"; exit 1; }
grep -E "^  (payloads|decode\(packed)" "$out/packed-sv.log"
n=$(grep -cE "$SV_PATTERN" "$out/packed-sv.log" || true)
[ "$n" = "0" ] || { echo "FAIL: $n shader validation reports in the packed path (see $out/packed-sv.log)"; exit 1; }
MTL_SHADER_VALIDATION=1 MTL_SHADER_VALIDATION_REPORT_TO_STDERR=1 $E packed-check control > "$out/packed-control.log" 2>&1 || true
grep -qE "$SV_PATTERN" "$out/packed-control.log" \
  || { echo "FAIL: shader validation did not report the packed unpack's deliberate out-of-bounds read"; exit 1; }
echo "packed path shader validation: 0 reports (and it does catch the unpack reading past its data when told a false length)"
# The encoder under validation on both entropy paths: the corpus, then fresh encoders on images that need a second
# attempt (ejm encode-retry; it read past the end of the arena before 2026-11-17).
for fb in 0 2000000; do
  echo "== encoder corpus and retries with Metal shader validation, EJM_FUSED_MAX_BLOCKS=$fb"
  EJM_FUSED_MAX_BLOCKS=$fb MTL_SHADER_VALIDATION=1 MTL_SHADER_VALIDATION_REPORT_TO_STDERR=1 MTL_DEBUG_LAYER=1 \
    $E encode-corpus > "$out/encode-sv$fb.log" 2>&1 || { echo "FAIL: encoder corpus under validation (see $out/encode-sv$fb.log)"; exit 1; }
  EJM_FUSED_MAX_BLOCKS=$fb MTL_SHADER_VALIDATION=1 MTL_SHADER_VALIDATION_REPORT_TO_STDERR=1 MTL_DEBUG_LAYER=1 \
    $E encode-retry >> "$out/encode-sv$fb.log" 2>&1 || { echo "FAIL: encode-retry under validation (see $out/encode-sv$fb.log)"; exit 1; }
  grep -E "^encoder: |^encode-retry: " "$out/encode-sv$fb.log"
  n=$(grep -cE "$SV_PATTERN" "$out/encode-sv$fb.log" || true)
  [ "$n" = "0" ] || { echo "FAIL: $n shader validation reports in the encoder (see $out/encode-sv$fb.log)"; exit 1; }
done
echo "encoder shader validation: 0 reports on both paths"
echo "== mixed-size sequences (one Decoder, one Encoder; each output = a fresh instance alone = libjpeg-turbo)"
$E mixed > "$out/mixed.log" || { grep "^FAIL" "$out/mixed.log"; echo "FAIL: mixed-size sequences (see $out/mixed.log)"; exit 1; }
echo "$(grep -c '^PASS' "$out/mixed.log") checks passed: $(tail -1 "$out/mixed.log")"
echo "== encoder fuzz (random sizes, strides, offsets, qualities, channels, subsamplings vs libjpeg-turbo)"
$E encode-fuzz "$out/encode-fuzz" "${ENC_FUZZ_ITERS:-$ENC_FUZZ_DEFAULT}" "${FUZZ_SEED:-1}" > "$out/encode-fuzz.log" \
  || { grep -E "FINDING|^encode-fuzz:" "$out/encode-fuzz.log" | head -20; echo "FAIL: encoder fuzz (see $out/encode-fuzz.log)"; exit 1; }
tail -1 "$out/encode-fuzz.log"
echo "== C example";       ./scripts/c-example.sh
echo "== Swift example";   ./scripts/swift-example.sh
# Every step passed: record the run, then build the exactness record from this directory alone (ejm exactness
# refuses on a missing or failed step; copy it to results/exactness.json to commit it).
commit="$(git rev-parse HEAD 2>/dev/null || echo unknown)"
dirty="$([ -n "$(git status --porcelain 2>/dev/null)" ] && echo true || echo false)"
cat > "$out/run.json" <<JSON
{"status": "passed", "run_id": "$(basename "$out")", "commit": "$commit", "uncommitted_changes": $dirty,
 "date": "$(date +%Y-%m-%dT%H:%M:%S%z)", "libjpeg_turbo_runtime": "$rt", "fuzz_iterations": ${FUZZ_ITERS:-$FUZZ_DEFAULT},
 "sv_fuzz_iterations": ${SV_ITERS:-$SV_DEFAULT}, "encode_fuzz_iterations": ${ENC_FUZZ_ITERS:-$ENC_FUZZ_DEFAULT}, "sv_pattern": "$SV_PATTERN",
 "sv_logs": ["fuzz-sv.log", "packed-sv.log", "encode-sv0.log", "encode-sv2000000.log"],
 "sv_controls": ["oob-selfcheck.log", "packed-control.log"]}
JSON
# ejm exactness refuses another libjpeg-turbo than 3.2.0 and uncommitted changes unless told, and then names the
# override in the record: here it is told, with a warning, so such a run still ends (a record with overrides is not
# one to commit as results/exactness.json)
xflags=()
[ "$rt" = "3.2.0" ] || { echo "WARNING: libjpeg-turbo $rt: the exactness record names it (--allow-runtime)"; xflags+=(--allow-runtime); }
[ "$dirty" = false ] || { echo "WARNING: uncommitted changes: the exactness record names them (--allow-dirty); commit and rerun for a record to commit"; xflags+=(--allow-dirty); }
echo "== exactness record"; $E exactness "$out" "$out/exactness.json" ${xflags[@]+"${xflags[@]}"}
echo "ALL PASSED ($out)"
